create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  first_name text not null default '',
  middle_name text not null default '',
  surname text not null default '',
  institution_domain text not null default '',
  requested_role text not null default 'student' check (requested_role in ('student', 'facilitator')),
  role text not null default 'student' check (role in ('student', 'facilitator')),
  created_at timestamptz not null default now()
);

create table public.assignments (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  due_date date not null,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.exam_events (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  test_title text not null,
  event_type text not null,
  note text not null,
  severity text not null default 'Review' check (severity in ('Review', 'Logged')),
  occurred_at timestamptz not null default now()
);

create index assignments_created_by_idx on public.assignments(created_by);
create index assignments_due_date_idx on public.assignments(due_date);
create index exam_events_student_id_idx on public.exam_events(student_id);
create index exam_events_occurred_at_idx on public.exam_events(occurred_at desc);
