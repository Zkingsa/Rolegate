create table if not exists public.exam_events (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  test_title text not null,
  event_type text not null,
  note text not null,
  severity text not null default 'Review' check (severity in ('Review', 'Logged')),
  occurred_at timestamptz not null default now()
);

create index if not exists exam_events_student_id_idx on public.exam_events(student_id);
create index if not exists exam_events_occurred_at_idx on public.exam_events(occurred_at desc);

alter table public.exam_events enable row level security;

drop policy if exists "Students can log their own exam events" on public.exam_events;
create policy "Students can log their own exam events"
on public.exam_events for insert
to authenticated
with check ((select auth.uid()) = student_id);

drop policy if exists "Facilitators can review exam events" on public.exam_events;
create policy "Facilitators can review exam events"
on public.exam_events for select
to authenticated
using (
  exists (
    select 1
    from public.profiles
    where profiles.id = (select auth.uid())
      and profiles.role = 'facilitator'
  )
);
